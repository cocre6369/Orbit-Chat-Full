DROP_WORDS = {"face", "with", "sign", "symbol", "squared", "negative", "emoji"}


def in_ranges(cp, ranges):
    return any(a <= cp <= b for a, b in ranges)


def keywords(cp):
    name = unicodedata.name(chr(cp), "").lower()
    words = [w for w in name.replace("-", " ").split() if w not in DROP_WORDS]
    return " ".join(words)[:40]


def build():
    seen = set()
    out = []
    for cat, ranges in CATEGORIES:
        items = []
        for a, b in ranges:
            for cp in range(a, b + 1):
                if cp in seen:
                    continue
                ch = chr(cp)
                if not unicodedata.name(ch, None) or unicodedata.category(ch) in ("Cn", "Co", "Cs"):
                    continue  # unassigned in this Python's Unicode version
                seen.add(cp)
                glyph = ch + ("\uFE0F" if cp < 0x1F000 or in_ranges(cp, TEXT_DEFAULT) else "")
                items.append([glyph, keywords(cp)])
        out.append([cat, items])
    return out


def main():
    data = build()
    body = json.dumps({"categories": data}, ensure_ascii=False, separators=(",", ":"))
    js = ("/* Orbit — local emoji dataset (generated by scripts/gen-emoji.py from Python's unicodedata; no network). */\n"
          "(function(root){'use strict';if(root.OrbitEmoji)return;\n"
          f"root.OrbitEmoji={body};\n"
          "})(typeof globalThis!=='undefined'?globalThis:self);\n")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(js)
    total = sum(len(items) for _, items in data)
    print(f"wrote {OUT}: {total} emoji in {len(data)} categories (Unicode {unicodedata.unidata_version})")
    for cat, items in data:
        print(f"  {cat}: {len(items)}")


if __name__ == "__main__":
    main()
